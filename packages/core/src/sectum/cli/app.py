app = typer.Typer(
    name="sectum",
    help="Sectum AI - multi-tenant AI verification.",
    no_args_is_help=True,
    add_completion=False,
)


def _version_callback(value: bool) -> None:
    """Print the CLI version and exit when ``--version`` is passed."""
    if value:
        typer.echo(f"sectum {__version__}")
        raise typer.Exit


@app.callback()
def main(
    version: Annotated[
        bool,
        typer.Option(
            "--version",
            help="Show the Sectum AI CLI version and exit.",
            callback=_version_callback,
            is_eager=True,
        ),
    ] = False,
) -> None:
    """Sectum AI - multi-tenant AI verification."""


@app.command(name="adapters")
def list_adapters() -> None:
    """List the installed adapters and their capabilities."""
    registry = AdapterRegistry()
    for fake in (
        FakeVectorStore(),
        FakeRAGPipeline(),
        FakeObservability(),
        FakeAgent(),
        FakeMCP(),
        FakeCache(),
        FakeModel(),
        FakeMemory(),
    ):
        registry.register(fake)
    typer.echo(f"{'ADAPTER':<22}{'FAMILY':<18}CAPABILITIES")
    for adapter in registry.all():
        capabilities = ", ".join(sorted(c.value for c in adapter.capabilities)) or "(none)"
        typer.echo(f"{adapter.name:<22}{adapter.family.value:<18}{capabilities}")


def _load_substrate(workdir: Path) -> Substrate:
    """Load the seeded substrate from ``workdir``, or exit with a config error."""
    path = workdir / "substrate.json"
    if not path.exists():
        typer.echo(f"no substrate at {path}; run 'sectum seed' first", err=True)
        raise typer.Exit(code=3)
    return Substrate.model_validate_json(path.read_text())


def _load_run(workdir: Path) -> RunResult:
    """Load the recorded run from ``workdir``, or exit with a config error."""
    path = workdir / "run.json"
    if not path.exists():
        typer.echo(f"no run at {path}; run 'sectum probe' first", err=True)
        raise typer.Exit(code=3)
    return RunResult.model_validate_json(path.read_text())


def _per_probe_counts(findings: list[Finding]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for finding in findings:
        counts[finding.probe_id] = counts.get(finding.probe_id, 0) + 1
    return counts


def _resolve_target(substrate: Substrate, name: str | None) -> UUID:
    """Resolve a target tenant by display name, defaulting to the first tenant."""
    if name is None:
        return substrate.tenants[0].tenant_id
    for tenant in substrate.tenants:
        if tenant.display_name.lower() == name.lower():
            return tenant.tenant_id
    available = ", ".join(tenant.display_name for tenant in substrate.tenants)
    typer.echo(f"unknown tenant '{name}'; available: {available}", err=True)
    raise typer.Exit(code=3)


@app.command()
def seed(
    scenario_seed: Annotated[int, typer.Option("--seed", help="Scenario seed.")] = 2026,
    workdir: Annotated[Path, typer.Option(help="Directory for run artifacts.")] = _DEFAULT_WORKDIR,
) -> None:
    """Provision synthetic tenants, generate corpora, and plant canary markers."""
    substrate = build_substrate(default_scenario(seed=scenario_seed))
    workdir.mkdir(parents=True, exist_ok=True)
    path = workdir / "substrate.json"
    path.write_text(substrate.model_dump_json(indent=2))
    typer.echo(
        f"seeded {len(substrate.tenants)} tenants and "
        f"{len(substrate.documents)} documents -> {path}"
    )


@app.command()
def probe(
    workdir: Annotated[
        Path, typer.Option(help="Directory holding the seeded substrate.")
    ] = _DEFAULT_WORKDIR,
    only: Annotated[
        str | None, typer.Option("--probe", help="Run only the probe with this id.")
    ] = None,
) -> None:
    """Run the probe suite against the seeded demo stack and record the findings."""
    substrate = _load_substrate(workdir)
    suite = _SUITE
    if only is not None:
        suite = tuple(instance for instance in _SUITE if instance.id == only)
        if not suite:
            available = ", ".join(instance.id for instance in _SUITE)
            typer.echo(f"unknown probe '{only}'; available: {available}", err=True)
            raise typer.Exit(code=3)
    vector = FakeVectorStore(shared_index=True)
    cache = FakeCache(tenant_scoped=False)
    model = FakeModel(adapter_bleed=True)
    mcp = FakeMCP(confused_deputy=True, token_passthrough=True)
    memory = FakeMemory(shared_memory=True)
    for tenant in substrate.tenants:
        documents = [doc for doc in substrate.documents if doc.tenant_id == tenant.tenant_id]
        vector.upsert(tenant.tenant_id, documents)
    for marker in substrate.manifest.markers:
        if marker.marker_type is MarkerType.HARD_CANARY:
            mcp.provision(
                marker.owner_tenant_id,
                marker.marker_id,
                f"MCP resource. Reference: {marker.plaintext}",
            )
    runner = Runner(substrate, vector=vector, cache=cache, model=model, mcp=mcp, memory=memory)

    started = datetime.now(UTC)
    step_results: list[StepResult] = []
    for probe_instance in suite:
        step_results.extend(runner.run_per_step(probe_instance))
    finished = datetime.now(UTC)

    findings = tuple(dedupe_findings(finding for _, group in step_results for finding in group))
    confirmed = confirmed_findings(findings)
    bleed_steps = [
        result for result in step_results if result[0].probe_id == RagEntityBleedProbe.id
    ]
    run = RunResult(
        run_id=f"run-{substrate.scenario.scenario_id}",
        scenario_hash=canonical_hash(substrate.scenario),
        manifest_hash=canonical_hash(substrate.manifest),
        started_at=started,
        finished_at=finished,
        adapter_versions={
            vector.name: __version__,
            cache.name: __version__,
            model.name: __version__,
            mcp.name: __version__,
            memory.name: __version__,
        },
        probe_versions={instance.id: __version__ for instance in suite},
        findings=findings,
        metrics=RunMetrics(
            confirmed_findings=len(confirmed),
            retrieval_pivot_rate=retrieval_pivot_rate(bleed_steps) if bleed_steps else None,
            per_probe_findings=_per_probe_counts(confirmed),
        ),
    )
    path = workdir / "run.json"
    path.write_text(run.model_dump_json(indent=2))
    plural = "" if len(suite) == 1 else "s"
    typer.echo(f"ran {len(suite)} probe{plural}: {len(confirmed)} confirmed cross-tenant findings")
    if run.metrics.retrieval_pivot_rate is not None:
        typer.echo(f"retrieval-pivot rate: {run.metrics.retrieval_pivot_rate:.0%}")
    typer.echo(f"run recorded -> {path}")
    if confirmed:
        raise typer.Exit(code=2)


@app.command()
def report(
    workdir: Annotated[
        Path, typer.Option(help="Directory holding the substrate and run.")
    ] = _DEFAULT_WORKDIR,
) -> None:
    """Assemble a tamper-evident evidence pack (JSON and PDF) from the run."""
    substrate = _load_substrate(workdir)
    run = _load_run(workdir)
    pack = build_evidence_pack(run, substrate.manifest, control_mappings=control_mappings())
    json_path = workdir / "evidence.json"
    json_path.write_text(pack.model_dump_json(indent=2))
    pdf_path = workdir / "audit-pack.pdf"
    render_audit_pack(pack, pdf_path)
    typer.echo(f"evidence pack -> {json_path}")
    typer.echo(f"audit pack -> {pdf_path}")


@app.command()
def verify(
    pack: Annotated[Path, typer.Argument(help="Path to an evidence.json pack.")],
) -> None:
    """Independently verify a tamper-evident evidence pack."""
    if not pack.exists():
        typer.echo(f"no evidence pack at {pack}", err=True)
        raise typer.Exit(code=3)
    evidence = EvidencePack.model_validate_json(pack.read_text())
    result = verify_pack(evidence)
    for check in result.checks:
        typer.echo(f"[{'ok' if check.ok else 'FAIL'}] {check.name}: {check.detail}")
    if not result.passed:
        typer.echo("VERIFICATION FAILED", err=True)
        raise typer.Exit(code=4)
    typer.echo("VERIFIED: the evidence pack is intact")


@app.command()
def erasure(
    target_tenant: Annotated[
        str | None, typer.Option("--target-tenant", help="Tenant display name.")
    ] = None,
    soft_delete: Annotated[
        bool, typer.Option("--soft-delete", help="Model a store that fails erasure.")
    ] = False,
    workdir: Annotated[
        Path, typer.Option(help="Directory holding the seeded substrate.")
    ] = _DEFAULT_WORKDIR,
) -> None:
    """Run the GDPR Article 17 erasure-verification workflow (Class 11, the wedge)."""
    substrate = _load_substrate(workdir)
    target = _resolve_target(substrate, target_tenant)
    store = FakeVectorStore(soft_delete=soft_delete)
    for tenant in substrate.tenants:
        documents = [doc for doc in substrate.documents if doc.tenant_id == tenant.tenant_id]
        store.upsert(tenant.tenant_id, documents)

    started = datetime.now(UTC)
    report = ErasureProbe(substrate, vector=store).run(target)
    finished = datetime.now(UTC)

    run = RunResult(
        run_id=f"erasure-{target.hex[:8]}",
        scenario_hash=canonical_hash(substrate.scenario),
        manifest_hash=canonical_hash(substrate.manifest),
        started_at=started,
        finished_at=finished,
        adapter_versions={store.name: __version__},
        probe_versions={ErasureProbe.id: __version__},
        findings=report.findings,
        metrics=RunMetrics(
            confirmed_findings=len(report.findings),
            erasure_residue={
                surface.surface.value: surface.residual_after for surface in report.surfaces
            },
        ),
    )
    pack = build_evidence_pack(run, substrate.manifest, control_mappings=control_mappings())
    json_path = workdir / "erasure-evidence.json"
    json_path.write_text(pack.model_dump_json(indent=2))
    pdf_path = workdir / "erasure-attestation.pdf"
    render_audit_pack(pack, pdf_path)

    for surface in report.surfaces:
        typer.echo(
            f"{surface.surface.value}: {surface.markers_before} markers before, "
            f"{surface.residual_after} after -> {surface.verdict}"
        )
    typer.echo(f"erasure attestation -> {json_path}, {pdf_path}")
    if report.erased:
        scanned = ", ".join(surface.surface.value for surface in report.surfaces)
        typer.echo(f"ERASURE VERIFIED: no residual marker on {scanned}.")
        return
    if any(surface.residual_after > 0 for surface in report.surfaces):
        typer.echo("ERASURE FAILED: residual data remains.", err=True)
        raise typer.Exit(code=2)
    typer.echo(
        "ERASURE INCONCLUSIVE: the target tenant's markers were not found, "
        "so erasure cannot be attested.",
        err=True,
    )
    raise typer.Exit(code=3)


@app.command()
def init(
    output: Annotated[
        Path, typer.Option(help="Path for the generated config file.")
    ] = _DEFAULT_CONFIG,
    force: Annotated[
        bool, typer.Option("--force", help="Overwrite an existing config file.")
    ] = False,
) -> None:
    """Scaffold a sectum.yaml configuration file."""
    if output.exists() and not force:
        typer.echo(f"{output} already exists; pass --force to overwrite", err=True)
        raise typer.Exit(code=3)
    output.write_text(_CONFIG_TEMPLATE)
    typer.echo(f"wrote {output}")


@app.command()
def baseline(
    workdir: Annotated[
        Path, typer.Option(help="Directory holding the recorded run.")
    ] = _DEFAULT_WORKDIR,
    save: Annotated[
        bool, typer.Option("--save", help="Save the current run's metrics as the baseline.")
    ] = False,
    compare: Annotated[
        bool,
        typer.Option("--compare", help="Compare the current run against the saved baseline."),
    ] = False,
) -> None:
    """Save a regression baseline from the current run, or compare against it."""
    run = _load_run(workdir)
    baseline_path = workdir / "baseline.json"
    if save:
        baseline_path.write_text(run.metrics.model_dump_json(indent=2))
        typer.echo(f"baseline saved -> {baseline_path}")
        return
    if not compare:
        typer.echo("pass --save to record a baseline or --compare to check against it", err=True)
        raise typer.Exit(code=3)
    if not baseline_path.exists():
        typer.echo(f"no baseline at {baseline_path}; run 'sectum baseline --save' first", err=True)
        raise typer.Exit(code=3)
    saved = RunMetrics.model_validate_json(baseline_path.read_text())
    comparison = compare_metrics(saved, run.metrics)
    for delta in comparison.deltas:
        verdict = "REGRESSED" if delta.regressed else "ok"
        typer.echo(f"[{verdict}] {delta.name}: {delta.baseline:g} -> {delta.current:g}")
    if comparison.regressed:
        typer.echo("BASELINE REGRESSION: a metric moved in the worse direction.", err=True)
        raise typer.Exit(code=2)
    typer.echo("no regression against the baseline")


if __name__ == "__main__":  # pragma: no cover
    app()
